# ----------------------------
# Basic Assignment
# ----------------------------

name = "John"

print(name)

# ----------------------------
# Reassignment
# ----------------------------

age = 22

print(age)

age = 23

print(age)

# ----------------------------
# Multiple Assignment
# ----------------------------

student_name, student_age, student_course = "John", 29, "Computer"

print(student_name)
print(student_age)
print(student_course)

# ----------------------------
# Chain Assignment
# ----------------------------

x = y = z = 500

print(x)
print(y)
print(z)

# ----------------------------
# Variable Swapping
# ----------------------------

a = 10
b = 20

a, b = b, a

print(a)
print(b)

# ----------------------------
# Sequence Unpacking
# ----------------------------

colors = ["Red", "Green", "Blue"]

red, green, blue = colors

print(red)
print(green)
print(blue)